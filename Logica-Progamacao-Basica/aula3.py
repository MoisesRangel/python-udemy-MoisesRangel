'''
Python = Linguagem de programação
Tipo de tipagem = Dinâmica/Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
'''
print(123) # ele dinamiacamente entendeu que é um numero do tipo inteiro
# Aspas simples
print('Moises Rangel') # ele dinamicamente entendeu que é um texto do tipo string
print('Moises "Rangel"') # um macete pra evitar usar o r antes é inverter as aspas ao escrever os argumentos assim o interpretador printa normalmente o que esta dentro das aspas duplas
# Aspas duplas
print("Moises Rangel") # funciona também com aspas duplas
# Escape
print("Moises \" Rangel")# essa contra barra informa ao interpretador que é para pular o proximo caractere
# r 
print(r"Moises \" Rangel") # essa letra r informa ao interpretador que é para ignorar a contra barra e imprimir o que está dentro das aspas